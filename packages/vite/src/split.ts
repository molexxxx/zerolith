/**
 * The modules a project means to load as chunks of their own: the views a
 * route table declares with `lazy()` from `@zerolith/router`, and the
 * locale modules of a message index compiled by `zerolith-i18n`. A static
 * import of one of them makes the bundler put it in the importing chunk,
 * which the build check reports. Pure work over the parser's tree.
 */
import { type AstNode, walk } from "./ast.js";
import type { ModuleParser } from "./transform.js";

/** The start of every module `zerolith-i18n` writes. */
export const MESSAGES_HEADER: string = "// Generated by @zerolith/i18n";

const ROUTER = "@zerolith/router";

/** A dynamic import that is meant to stay a chunk of its own. */
export interface SplitImport
{
    /** The specifier as written in the `import()`. */
    readonly specifier: string;
    /** `route` for a view declared with `lazy()`, `locale` for a module of a compiled message index. */
    readonly kind: "route" | "locale";
    /** Offset of the `import()` in the module. */
    readonly offset: number;
}

interface ImportExpression extends AstNode
{
    type: "ImportExpression";
    source: AstNode & { value?: unknown };
}

interface ImportDeclaration extends AstNode
{
    type: "ImportDeclaration";
    source: { value: string };
    importKind?: string;
    specifiers: readonly (AstNode & { local: AstNode & { name: string }; imported?: AstNode & { name?: string; value?: string } })[];
}

interface CallExpression extends AstNode
{
    type: "CallExpression";
    callee: AstNode & { name?: string; object?: AstNode & { name?: string }; property?: AstNode & { name?: string }; computed?: boolean };
    arguments: readonly AstNode[];
}

/** Collects the `import()` calls with a string specifier under `node`. */
function literalImports(node: unknown, kind: SplitImport["kind"], found: SplitImport[]): void
{
    walk(node, (child) =>
    {
        if (child.type === "ImportExpression")
        {
            const { source } = child as ImportExpression;
            if (typeof source.value === "string")
            {
                found.push({ specifier: source.value, kind, offset: child.start });
            }
        }
        return true;
    });
}

/** The local names `lazy` from the router goes by in a module, and the namespaces the router is imported as. */
function routerBindings(body: readonly AstNode[]): { lazy: Set<string>; namespaces: Set<string> }
{
    const lazy = new Set<string>();
    const namespaces = new Set<string>();
    for (const statement of body)
    {
        if (statement.type !== "ImportDeclaration")
        {
            continue;
        }
        const declaration = statement as ImportDeclaration;
        if (declaration.source.value !== ROUTER || declaration.importKind === "type")
        {
            continue;
        }
        for (const specifier of declaration.specifiers)
        {
            if (specifier.type === "ImportNamespaceSpecifier")
            {
                namespaces.add(specifier.local.name);
            }
            else if (specifier.type === "ImportSpecifier" && (specifier.imported?.name ?? specifier.imported?.value) === "lazy")
            {
                lazy.add(specifier.local.name);
            }
        }
    }
    return { lazy, namespaces };
}

/**
 * The dynamic imports of a module that are meant to stay chunks of their
 * own, in source order: every `import()` with a string specifier inside the
 * loader passed to the router's `lazy()`, and every one in a compiled
 * message index. Any other module yields none.
 */
export function splitImports(code: string, id: string, parse: ModuleParser): SplitImport[]
{
    const messages = code.startsWith(MESSAGES_HEADER);
    if (!messages && !code.includes(ROUTER))
    {
        return [];
    }
    const { program, errors } = parse(id, code);
    if (errors.length > 0)
    {
        return [];
    }
    const found: SplitImport[] = [];
    if (messages)
    {
        literalImports(program.body, "locale", found);
        return found;
    }
    const { lazy, namespaces } = routerBindings(program.body);
    if (lazy.size === 0 && namespaces.size === 0)
    {
        return [];
    }
    walk(program.body, (node) =>
    {
        if (node.type !== "CallExpression")
        {
            return true;
        }
        const { callee, arguments: args } = node as CallExpression;
        const named = callee.type === "Identifier" && lazy.has(callee.name ?? "");
        const member = callee.type === "MemberExpression" && callee.computed !== true && callee.object?.type === "Identifier" && namespaces.has(callee.object.name ?? "") && callee.property?.name === "lazy";
        const loader = args[0];
        if ((named || member) && loader !== undefined)
        {
            literalImports(loader, "route", found);
            return false;
        }
        return true;
    });
    return found.toSorted((a, b) => a.offset - b.offset);
}
