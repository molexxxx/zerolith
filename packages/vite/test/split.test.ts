import { parseSync } from "vite";
import { describe, expect, it } from "vitest";
import { type ModuleParser, splitImports } from "@zerolith/vite";

const parse: ModuleParser = (filename, code) => parseSync(filename, code, { sourceType: "module", lang: filename.endsWith(".ts") ? "ts" : "js" });

function splits(code: string, id = "/src/routes.js"): string[]
{
    return splitImports(code, id, parse).map((split) => `${split.kind} ${split.specifier}`);
}

describe("splitImports", () =>
{
    it("finds the views a route table loads with lazy() from the router", () =>
    {
        expect(splits("import { defineRoutes, lazy } from \"@zerolith/router\";\nexport const routes = defineRoutes({\n    home: { path: \"/\", view: lazy(() => import(\"./views/home.js\")) },\n    release: { path: \"/r/:tag\", view: lazy(() => import(\"./views/release.js\").then((m) => m.view)) }\n});\n")).toEqual(["route ./views/home.js", "route ./views/release.js"]);
    });

    it("follows an alias, a namespace import, and an async loader, and parses TypeScript", () =>
    {
        expect(splits("import { lazy as later } from \"@zerolith/router\";\nlater(() => import(\"./a.js\"));\n")).toEqual(["route ./a.js"]);
        expect(splits("import * as router from \"@zerolith/router\";\nrouter.lazy(async () => (await import(\"./b.js\")).view);\n")).toEqual(["route ./b.js"]);
        expect(splits("import { lazy } from \"@zerolith/router\";\nexport const v = lazy<{ id: string }, unknown>(() => import(\"./c.ts\"));\n", "/src/routes.ts")).toEqual(["route ./c.ts"]);
    });

    it("ignores lazy from elsewhere, a type import, dynamic imports outside lazy(), and computed specifiers", () =>
    {
        expect(splits("import { lazy } from \"./mine.js\";\nlazy(() => import(\"./d.js\"));\n")).toEqual([]);
        expect(splits("import type { lazy } from \"@zerolith/router\";\nimport(\"./e.js\");\n", "/src/types.ts")).toEqual([]);
        expect(splits("import { lazy } from \"@zerolith/router\";\nimport(\"./f.js\");\nlazy(() => import(name));\n")).toEqual([]);
    });

    it("treats every dynamic import of a compiled message index as a locale", () =>
    {
        const index = "// Generated by @zerolith/i18n. Do not edit; regenerate instead.\nexport const loaders = {\n    \"de\": () => import(\"./de.ts\"),\n    \"en\": () => import(\"./en.ts\")\n};\n";
        expect(splits(index, "/src/messages/index.ts")).toEqual(["locale ./de.ts", "locale ./en.ts"]);
        expect(splits("// A comment that mentions @zerolith/i18n.\nexport const loaders = { en: () => import(\"./en.ts\") };\n", "/src/other.ts")).toEqual([]);
    });
});
