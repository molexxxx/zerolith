import { mkdir, mkdtemp, rm, writeFile } from "node:fs/promises";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { fileURLToPath } from "node:url";
import { build } from "vite";
import { afterAll, beforeAll, describe, expect, it } from "vitest";
import { zerolith } from "@zerolith/vite";

/**
 * Builds a one-file application for production with the built core aliased
 * to its production entry, then to its development entry: the first passes
 * and the second fails with the plugin's message, and a development-mode
 * build with the development entry passes because nothing is asserted there.
 */

const repoRoot = fileURLToPath(new URL("../../../", import.meta.url));
const productionEntry = join(repoRoot, "packages/zerolith/dist/production/index.js");
const developmentEntry = join(repoRoot, "packages/zerolith/dist/index.js");
const routerEntry = join(repoRoot, "packages/router/dist/index.js");

let folder: string;

let valueFolder: string;

let eagerFolder: string;

let lazyFolder: string;

const MESSAGES_INDEX = "// Generated by @zerolith/i18n. Do not edit; regenerate instead.\nexport const loaders = { de: () => import(\"./de.js\"), en: () => import(\"./en.js\") };\n";

/** Writes an application whose route table loads two views lazily and whose messages load per locale. */
async function application(root: string, main: string): Promise<void>
{
    await mkdir(join(root, "views"), { recursive: true });
    await mkdir(join(root, "messages"), { recursive: true });
    await writeFile(join(root, "index.html"), INDEX);
    await writeFile(join(root, "main.js"), main);
    await writeFile(join(root, "views/release.js"), "export const view = \"release\";\n");
    await writeFile(join(root, "views/notes.js"), "export const view = \"notes\";\n");
    await writeFile(join(root, "messages/index.js"), MESSAGES_INDEX);
    await writeFile(join(root, "messages/de.js"), "export const hello = \"Hallo\";\n");
    await writeFile(join(root, "messages/en.js"), "export const hello = \"Hello\";\n");
}

const ROUTES = "import { lazy } from \"@zerolith/router\";\nimport { loaders } from \"./messages/index.js\";\nexport const routes = { release: lazy(() => import(\"./views/release.js\")), notes: lazy(() => import(\"./views/notes.js\")) };\nconsole.log(routes, loaders);\n";

const INDEX = "<!doctype html><html><body><div id=\"app\"></div><script type=\"module\" src=\"/main.js\"></script></body></html>";

beforeAll(async () =>
{
    folder = await mkdtemp(join(tmpdir(), "zerolith-build-"));
    await writeFile(join(folder, "index.html"), INDEX);
    await writeFile(join(folder, "main.js"), "import { html, render } from \"zerolith\";\nrender(html`<p>built</p>`, \"#app\");\n");
    valueFolder = await mkdtemp(join(tmpdir(), "zerolith-build-value-"));
    await writeFile(join(valueFolder, "index.html"), INDEX);
    await writeFile(join(valueFolder, "main.js"), "import { html, render } from \"zerolith\";\nconst tag = html;\nrender(tag`<p>built</p>`, \"#app\");\n");
    eagerFolder = await mkdtemp(join(tmpdir(), "zerolith-build-eager-"));
    await application(eagerFolder, `import { view } from "./views/release.js";\nimport { hello } from "./messages/de.js";\nconsole.log(view, hello);\n${ROUTES}`);
    lazyFolder = await mkdtemp(join(tmpdir(), "zerolith-build-lazy-"));
    await application(lazyFolder, ROUTES);
});

afterAll(async () =>
{
    await rm(folder, { recursive: true, force: true });
    await rm(valueFolder, { recursive: true, force: true });
    await rm(eagerFolder, { recursive: true, force: true });
    await rm(lazyFolder, { recursive: true, force: true });
});

interface Built
{
    output: { type: string; code?: string }[];
}

function run(entry: string, mode: string, options: Parameters<typeof zerolith>[0] = {}, root = folder): Promise<unknown>
{
    return build({
        root,
        configFile: false,
        envFile: false,
        logLevel: "silent",
        mode,
        plugins: [zerolith(options)],
        resolve: { alias: { zerolith: entry } },
        build: { write: false, minify: false }
    });
}

/** Builds one of the routed applications for production, with the router resolved to its built entry. */
function routed(root: string, extra: Record<string, unknown> = {}): Promise<unknown>
{
    return build({
        root,
        configFile: false,
        envFile: false,
        logLevel: "silent",
        mode: "production",
        plugins: [zerolith()],
        resolve: { alias: [{ find: /^zerolith$/, replacement: productionEntry }, { find: /^@zerolith\/router$/, replacement: routerEntry }] },
        build: { write: false, minify: false, ...extra }
    });
}

/** The code of every chunk a build produced, joined. */
async function built(entry: string, mode: string, options: Parameters<typeof zerolith>[0] = {}): Promise<string>
{
    const result = await run(entry, mode, options);
    const builds = (Array.isArray(result) ? result : [result]) as Built[];
    return builds.flatMap((item) => item.output).map((item) => item.code ?? "").join("\n");
}

describe("the build check", () =>
{
    it("passes a production build on the production entry", { timeout: 60000 }, async () =>
    {
        await expect(run(productionEntry, "production")).resolves.toBeDefined();
    });

    it("fails a production build that bundled the development entry", { timeout: 60000 }, async () =>
    {
        await expect(run(developmentEntry, "production")).rejects.toThrow(/development build of zerolith reached the production output/);
    });

    it("leaves a development-mode build alone", { timeout: 60000 }, async () =>
    {
        await expect(run(developmentEntry, "development")).resolves.toBeDefined();
    });
});

describe("the prepare pass", () =>
{
    it("prepares every template and drops the scanner", { timeout: 60000 }, async () =>
    {
        const code = await built(productionEntry, "production");
        expect(code).toContain("[\"<p>built</p>\"], \"<p>built</p>\", []");
        expect(code).not.toContain("html`<p>built</p>`");
        expect(code).toContain("template_not_prepared");
        expect(code).not.toContain("binding_in_comment");
    });

    it("keeps the scanner and the literals with prepare: false", { timeout: 60000 }, async () =>
    {
        const code = await built(productionEntry, "production", { prepare: false });
        expect(code).toContain("html`<p>built</p>`");
        expect(code).toContain("binding_in_comment");
        expect(code).not.toContain("template_not_prepared");
    });

    it("fails when html is used other than as a tag", { timeout: 60000 }, async () =>
    {
        await expect(run(productionEntry, "production", {}, valueFolder)).rejects.toThrow(/other than as a template tag/);
    });
});

describe("the split check", () =>
{
    it("keeps lazy route views and compiled locales in chunks of their own", { timeout: 60000 }, async () =>
    {
        const result = await routed(lazyFolder);
        const builds = (Array.isArray(result) ? result : [result]) as { output: { type: string; fileName: string; isEntry?: boolean }[] }[];
        const lazyChunks = builds.flatMap((item) => item.output).filter((item) => item.type === "chunk" && item.isEntry !== true).map((item) => item.fileName.split("/").pop()?.split("-")[0]);
        expect(lazyChunks.toSorted()).toEqual(["de", "en", "notes", "release"]);
    });

    it("fails a client build that imports a lazy view or a locale statically, naming each", { timeout: 60000 }, async () =>
    {
        const failure = routed(eagerFolder);
        await expect(failure).rejects.toThrow(/lazy_module_not_split: views\/release\.js is a route view loaded with lazy\(\) in main\.js but is also imported statically by main\.js; messages\/de\.js is a locale of a compiled message index in messages\/index\.js but is also imported statically by main\.js\./);
        await expect(failure).rejects.not.toThrow(/views\/notes\.js|messages\/en\.js/);
    });

    it("leaves a server build alone", { timeout: 60000 }, async () =>
    {
        await expect(routed(eagerFolder, { ssr: "main.js" })).resolves.toBeDefined();
    });
});
