//! The modules a project means to load as chunks of their own, ported from
//! the Vite plugin's `split.ts`: the views a route table declares with
//! `lazy()` from `@zerolith/router`, and the locale modules of a message
//! index compiled by `zerolith-i18n`. `zerolith build` fails when one of
//! them is also imported statically, which would merge it into the
//! importing chunk.

use std::collections::HashSet;

use oxc_allocator::Allocator;
use oxc_ast::ast::{
    Argument, CallExpression, Expression, ImportDeclarationSpecifier, ImportExpression, Statement,
};
use oxc_ast_visit::{Visit, walk};
use oxc_parser::Parser;
use oxc_span::SourceType;

use crate::transform::parse_errors;

/// The start of every module `zerolith-i18n` writes.
pub const MESSAGES_HEADER: &str = "// Generated by @zerolith/i18n";

const ROUTER: &str = "@zerolith/router";

/// Why a dynamic import is meant to stay a chunk of its own.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum SplitKind {
    /// A view declared with `lazy()`.
    Route,
    /// A locale module of a compiled message index.
    Locale,
}

/// A dynamic import that is meant to stay a chunk of its own.
#[derive(Clone, Debug, PartialEq, Eq)]
pub struct SplitImport {
    /// The specifier as written in the `import()`.
    pub specifier: String,
    pub kind: SplitKind,
    /// Byte offset of the `import()` in the module.
    pub offset: u32,
}

/// Collects every `import()` with a string specifier under a node.
struct Imports {
    kind: SplitKind,
    found: Vec<SplitImport>,
}

impl<'a> Visit<'a> for Imports {
    fn visit_import_expression(&mut self, it: &ImportExpression<'a>) {
        if let Expression::StringLiteral(source) = &it.source
            && let Some(specifier) = source.value.as_str()
        {
            self.found.push(SplitImport {
                specifier: specifier.to_string(),
                kind: self.kind,
                offset: it.span.start,
            });
        }
        walk::walk_import_expression(self, it);
    }
}

/// Finds the loaders passed to the router's `lazy()` and collects their imports.
struct LazyCalls {
    lazy: HashSet<String>,
    namespaces: HashSet<String>,
    found: Vec<SplitImport>,
}

impl LazyCalls {
    fn is_lazy(&self, callee: &Expression<'_>) -> bool {
        match callee {
            Expression::Identifier(name) => self.lazy.contains(name.name.as_str()),
            Expression::StaticMemberExpression(member) => {
                matches!(&member.object, Expression::Identifier(object) if self.namespaces.contains(object.name.as_str()))
                    && member.property.name == "lazy"
            }
            _ => false,
        }
    }
}

impl<'a> Visit<'a> for LazyCalls {
    fn visit_call_expression(&mut self, it: &CallExpression<'a>) {
        if self.is_lazy(&it.callee)
            && let Some(loader) = it.arguments.first()
        {
            let mut imports = Imports {
                kind: SplitKind::Route,
                found: Vec::new(),
            };
            if let Argument::SpreadElement(spread) = loader {
                imports.visit_expression(&spread.argument);
            } else if let Some(expression) = loader.as_expression() {
                imports.visit_expression(expression);
            }
            self.found.append(&mut imports.found);
            return;
        }
        walk::walk_call_expression(self, it);
    }
}

/// The dynamic imports of a module that are meant to stay chunks of their own, in source order: every `import()` with a string specifier inside the loader passed to the router's `lazy()`, and every one in a compiled message index. Any other module yields none.
pub fn split_imports(source: &str, source_type: SourceType) -> Vec<SplitImport> {
    let messages = source.starts_with(MESSAGES_HEADER);
    if !messages && !source.contains(ROUTER) {
        return Vec::new();
    }
    let allocator = Allocator::default();
    let parsed = Parser::new(&allocator, source, source_type).parse();
    if parse_errors(parsed.diagnostics, source).is_some() {
        return Vec::new();
    }
    if messages {
        let mut imports = Imports {
            kind: SplitKind::Locale,
            found: Vec::new(),
        };
        imports.visit_program(&parsed.program);
        return imports.found;
    }
    let mut calls = LazyCalls {
        lazy: HashSet::new(),
        namespaces: HashSet::new(),
        found: Vec::new(),
    };
    for statement in &parsed.program.body {
        let Statement::ImportDeclaration(declaration) = statement else {
            continue;
        };
        if declaration.source.value != ROUTER || declaration.import_kind.is_type() {
            continue;
        }
        for specifier in declaration.specifiers.iter().flatten() {
            match specifier {
                ImportDeclarationSpecifier::ImportSpecifier(import) => {
                    if import.imported.name() == "lazy" {
                        calls.lazy.insert(import.local.name.to_string());
                    }
                }
                ImportDeclarationSpecifier::ImportNamespaceSpecifier(import) => {
                    calls.namespaces.insert(import.local.name.to_string());
                }
                ImportDeclarationSpecifier::ImportDefaultSpecifier(_) => {}
            }
        }
    }
    if calls.lazy.is_empty() && calls.namespaces.is_empty() {
        return Vec::new();
    }
    calls.visit_program(&parsed.program);
    calls.found.sort_by_key(|split| split.offset);
    calls.found
}

#[cfg(test)]
mod tests {
    use super::{SplitKind, split_imports};
    use oxc_span::SourceType;

    fn splits(source: &str, source_type: SourceType) -> Vec<String> {
        split_imports(source, source_type)
            .iter()
            .map(|split| {
                let kind = match split.kind {
                    SplitKind::Route => "route",
                    SplitKind::Locale => "locale",
                };
                format!("{kind} {}", split.specifier)
            })
            .collect()
    }

    #[test]
    fn finds_lazy_views_through_names_aliases_and_namespaces() {
        assert_eq!(
            splits(
                "import { defineRoutes, lazy } from \"@zerolith/router\";\nexport const routes = defineRoutes({\n    home: { path: \"/\", view: lazy(() => import(\"./views/home.js\")) },\n    release: { path: \"/r/:tag\", view: lazy(() => import(\"./views/release.js\").then((m) => m.view)) }\n});\n",
                SourceType::mjs()
            ),
            ["route ./views/home.js", "route ./views/release.js"]
        );
        assert_eq!(
            splits(
                "import { lazy as later } from \"@zerolith/router\";\nlater(() => import(\"./a.js\"));\n",
                SourceType::mjs()
            ),
            ["route ./a.js"]
        );
        assert_eq!(
            splits(
                "import * as router from \"@zerolith/router\";\nrouter.lazy(async () => (await import(\"./b.js\")).view);\n",
                SourceType::mjs()
            ),
            ["route ./b.js"]
        );
        assert_eq!(
            splits(
                "import { lazy } from \"@zerolith/router\";\nexport const v = lazy<{ id: string }, unknown>(() => import(\"./c.ts\"));\n",
                SourceType::ts()
            ),
            ["route ./c.ts"]
        );
    }

    #[test]
    fn ignores_other_lazy_functions_type_imports_and_computed_specifiers() {
        assert!(
            splits(
                "import { lazy } from \"./mine.js\";\nlazy(() => import(\"./d.js\"));\n",
                SourceType::mjs()
            )
            .is_empty()
        );
        assert!(
            splits(
                "import type { lazy } from \"@zerolith/router\";\nimport(\"./e.js\");\n",
                SourceType::ts()
            )
            .is_empty()
        );
        assert!(
            splits(
                "import { lazy } from \"@zerolith/router\";\nimport(\"./f.js\");\nlazy(() => import(name));\n",
                SourceType::mjs()
            )
            .is_empty()
        );
    }

    #[test]
    fn treats_every_import_of_a_compiled_message_index_as_a_locale() {
        assert_eq!(
            splits(
                "// Generated by @zerolith/i18n. Do not edit; regenerate instead.\nexport const loaders = {\n    \"de\": () => import(\"./de.ts\"),\n    \"en\": () => import(\"./en.ts\")\n};\n",
                SourceType::ts()
            ),
            ["locale ./de.ts", "locale ./en.ts"]
        );
        assert!(
            splits(
                "// A comment that mentions @zerolith/i18n.\nexport const loaders = { en: () => import(\"./en.ts\") };\n",
                SourceType::ts()
            )
            .is_empty()
        );
    }
}
